/**
 * Logements de démonstration — aucune donnée réelle.
 *
 * Les quatre photos disponibles tournent ; chacune a son texte alternatif, parce
 * que l'absence d'alternative se voit à la revue d'accessibilité, pas au premier
 * coup d'œil. Aucune adresse exacte ni téléphone : ces champs n'existent pas dans
 * le type `Logement`, ils arrivent avec la confirmation.
 */
type Numero = 1 | 2 | 3 | 4;

/**
 * Une galerie : la photo principale d'abord, puis les autres. Chacune porte son
 * propre texte alternatif — une alternative recopiée d'une photo à l'autre ne vaut
 * pas mieux que pas d'alternative du tout (§C.6).
 */
const GALERIE = (principale: Numero, alts: string[]): { url: string; alt: string; principale?: boolean }[] => {
  const autres = ([1, 2, 3, 4] as Numero[]).filter((n) => n !== principale);
  return [
    { url: `/images/logement-${principale}.png`, alt: alts[0], principale: true },
    ...autres.map((n, i) => ({ url: `/images/logement-${n}.png`, alt: alts[i + 1] ?? alts[0] })),
  ];
};

